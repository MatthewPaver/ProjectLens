// Public real-case regression suite. Regenerates README.md with --write.
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { describe, it } from "node:test";
import { CASES, REPO, RESEARCH } from "./cases.mjs";

const require = createRequire(import.meta.url);
const engine = require(path.join(REPO, "docs/engine/projectlens-engine.js"));
const writeMode = process.argv.includes("--write") || process.env.WRITE_REAL_CASES === "1";
const results = [];

function xerFromPair(pair) {
  const dataDate = year => `${year}-03-31 00:00`;
  return (end, year, label) => [
    "ERMHDR\t20.12\t" + `${year}-03-31` + "\tProject\tadmin\tGMPP adapter\tdbxDatabaseNoName\tProject Management\tGBP",
    "%T\tPROJECT",
    "%F\tproj_id\tproj_short_name\tscd_end_date\tlast_recalc_date",
    `%R\t${pair.id}\t${pair.id}\t${end} 00:00\t${dataDate(year)}`,
    "%T\tTASK",
    "%F\ttask_id\tproj_id\ttask_code\ttask_name\ttask_type\tstatus_code\ttotal_float_hr_cnt\tearly_end_date",
    `%R\t1\t${pair.id}\tEND\tPublished project end date\tTT_FinMile\tTK_NotStart\t0\t${end} 00:00`,
    "",
  ].join("\r\n");
}

function loadPairNarrative(caseDef) {
  if (caseDef.pairFilter) {
    const pairsPath = path.join(RESEARCH, "gmpp_pairs.json");
    if (!fs.existsSync(pairsPath)) return null;
    const pairs = JSON.parse(fs.readFileSync(pairsPath, "utf8"));
    const pair = pairs.find(p =>
      p.id === caseDef.pairFilter.id
      && p.prevYear === caseDef.pairFilter.prevYear
      && p.year === caseDef.pairFilter.year,
    );
    if (!pair) return null;
    const make = xerFromPair(pair);
    return {
      previousText: make(pair.prevEnd, pair.prevYear),
      currentText: make(pair.curEnd, pair.year),
      narrative: pair.narrative,
      previousName: "previous.xer",
      currentName: "current.xer",
    };
  }
  const needed = [caseDef.previous, caseDef.current, caseDef.narrative];
  if (needed.some(p => !p || !fs.existsSync(p))) return null;
  return {
    previousText: fs.readFileSync(caseDef.previous, "utf8"),
    currentText: fs.readFileSync(caseDef.current, "utf8"),
    narrative: fs.readFileSync(caseDef.narrative, "utf8"),
    previousName: path.basename(caseDef.previous),
    currentName: path.basename(caseDef.current),
  };
}

function runCase(caseDef) {
  const loaded = loadPairNarrative(caseDef);
  if (!loaded) {
    return { skipped: true, reason: "fixture absent" };
  }
  const previous = engine.parseXerAssurance(loaded.previousText, loaded.previousName);
  const current = engine.parseXerAssurance(loaded.currentText, loaded.currentName);
  const review = engine.analyseReview(previous, current, loaded.narrative.trim(), { confirmedMatch: true });
  const contradiction = review.blockers.some(b => b.type === "Contradiction");
  return {
    skipped: false,
    contradiction,
    daysMoved: review.finishMovement,
    blockers: review.blockers.map(b => b.type),
  };
}

describe("public real-case regression", () => {
  for (const caseDef of CASES) {
    it(caseDef.title, () => {
      const actual = runCase(caseDef);
      if (actual.skipped) {
        if (caseDef.optional || caseDef.pairFilter) {
          results.push({ ...caseDef, status: "skipped", detail: actual.reason });
          return;
        }
        assert.fail(`Required fixture missing for ${caseDef.id}`);
      }
      const okContradiction = actual.contradiction === caseDef.expect.contradiction;
      const okDays = caseDef.expect.daysMoved === undefined
        || actual.daysMoved === caseDef.expect.daysMoved;
      results.push({
        ...caseDef,
        status: okContradiction && okDays ? "pass" : "fail",
        actualContradiction: actual.contradiction,
        actualDaysMoved: actual.daysMoved,
      });
      assert.equal(actual.contradiction, caseDef.expect.contradiction, `${caseDef.id} contradiction`);
      if (caseDef.expect.daysMoved !== undefined) {
        assert.equal(actual.daysMoved, caseDef.expect.daysMoved, `${caseDef.id} daysMoved`);
      }
    });
  }

  it("optionally writes the results table", () => {
    if (!writeMode) return;
    const lines = [
      "# Real-case regression results",
      "",
      "Regenerated by `node --test tests/real-cases/real-cases.test.mjs -- --write`.",
      "",
      "| id | title | kind | expect contradiction | result | days moved |",
      "|---|---|---|---|---|---|",
      ...results.map(row => {
        const expect = row.expect?.contradiction ? "yes" : "no";
        const result = row.status;
        const days = row.actualDaysMoved ?? row.expect?.daysMoved ?? "";
        return `| ${row.id} | ${row.title} | ${row.kind} | ${expect} | ${result} | ${days} |`;
      }),
      "",
    ];
    fs.writeFileSync(path.join(REPO, "tests/real-cases/README.md"), `${lines.join("\n")}\n`);
  });
});
